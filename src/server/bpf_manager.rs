    /// Delete an IPv4 policy rule from the two-level LPM.
    pub fn delete_policy_rule_v4(
        &mut self,
        src_key: &SrcLpmKeyV4,
        dst_key: &LpmKeyV4,
        rule_id: u64,
        direction: Direction,
    ) -> Result<()> {
        let src_key_bytes = src_key.as_bytes().to_vec();
        let (group_id, pin_path) = match direction {
            Direction::Ingress => self.ingress_registry.v4.get(&src_key_bytes),
            Direction::Egress => self.egress_registry.v4.get(&src_key_bytes),
        }
        .map(|(gid, p)| (*gid, p.clone()))
        .ok_or_else(|| anyhow!("No v4 group for src prefix {:?}", src_key))?;

        let inner_map = libbpf_rs::MapHandle::from_pinned_path(&pin_path)
            .context("open inner dst v4 map for delete")?;

        let dst_key_bytes = dst_key.as_bytes();
        let existing = inner_map
            .lookup(dst_key_bytes, MapFlags::ANY)?
            .ok_or_else(|| anyhow!("dst entry not found for rule {}", rule_id))?;
        let mut val = DstLpmValue::default();
        plain::copy_from_bytes(&mut val, &existing)
            .map_err(|e| anyhow!("Failed to parse DstLpmValue: {:?}", e))?;

        let count = val.count as usize;
        let pos = val.rules[..count]
            .iter()
            .position(|r| r.rule_id == rule_id)
            .ok_or_else(|| anyhow!("Rule {} not found in dst entry", rule_id))?;
        for i in pos..count - 1 {
            val.rules[i] = val.rules[i + 1];
        }
        val.rules[count - 1] = L4Rule::default();
        val.count -= 1;

        if val.count == 0 {
            inner_map
                .delete(dst_key_bytes)
                .context("delete dst LPM v4 entry")?;
            // If group is now empty, remove it entirely.
            if inner_map.keys().next().is_none() {
                let gkey = group_id.to_ne_bytes();
                match direction {
                    Direction::Ingress => {
                        if let Some(skel) = &mut self.xdp_skel {
                            let _ = skel.maps.src_groups_v4.delete(&gkey);
                            let _ = skel.maps.src_lpm_v4.delete(src_key.as_bytes());
                        }
                    }
                    Direction::Egress => {
                        if let Some(skel) = &mut self.tc_skel {
                            let _ = skel.maps.tc_src_groups_v4.delete(&gkey);
                            let _ = skel.maps.tc_src_lpm_v4.delete(src_key.as_bytes());
                        }
                    }
                }
                let _ = fs::remove_file(&pin_path);
                match direction {
                    Direction::Ingress => self.ingress_registry.v4.remove(&src_key_bytes),
                    Direction::Egress => self.egress_registry.v4.remove(&src_key_bytes),
                };
            }
        } else {
            inner_map
                .update(dst_key_bytes, val.as_bytes(), MapFlags::ANY)
                .context("update dst LPM v4 after rule removal")?;
        }
        debug!("Deleted policy v4 rule {} ({:?})", rule_id, direction);
        Ok(())
    }

    /// Delete an IPv6 policy rule from the two-level LPM.
    pub fn delete_policy_rule_v6(
        &mut self,
        src_key: &SrcLpmKeyV6,
        dst_key: &LpmKeyV6,
        rule_id: u64,
        direction: Direction,
    ) -> Result<()> {
        let src_key_bytes = src_key.as_bytes().to_vec();
        let (group_id, pin_path) = match direction {
            Direction::Ingress => self.ingress_registry.v6.get(&src_key_bytes),
            Direction::Egress => self.egress_registry.v6.get(&src_key_bytes),
        }
        .map(|(gid, p)| (*gid, p.clone()))
        .ok_or_else(|| anyhow!("No v6 group for src prefix {:?}", src_key))?;

        let inner_map = libbpf_rs::MapHandle::from_pinned_path(&pin_path)
            .context("open inner dst v6 map for delete")?;

        let dst_key_bytes = dst_key.as_bytes();
        let existing = inner_map
            .lookup(dst_key_bytes, MapFlags::ANY)?
            .ok_or_else(|| anyhow!("dst entry not found for rule {}", rule_id))?;
        let mut val = DstLpmValue::default();
        plain::copy_from_bytes(&mut val, &existing)
            .map_err(|e| anyhow!("Failed to parse DstLpmValue: {:?}", e))?;

        let count = val.count as usize;
        let pos = val.rules[..count]
            .iter()
            .position(|r| r.rule_id == rule_id)
            .ok_or_else(|| anyhow!("Rule {} not found in dst entry", rule_id))?;
        for i in pos..count - 1 {
            val.rules[i] = val.rules[i + 1];
        }
        val.rules[count - 1] = L4Rule::default();
        val.count -= 1;

        if val.count == 0 {
            inner_map
                .delete(dst_key_bytes)
                .context("delete dst LPM v6 entry")?;
            if inner_map.keys().next().is_none() {
                let gkey = group_id.to_ne_bytes();
                match direction {
                    Direction::Ingress => {
                        if let Some(skel) = &mut self.xdp_skel {
                            let _ = skel.maps.src_groups_v6.delete(&gkey);
                            let _ = skel.maps.src_lpm_v6.delete(src_key.as_bytes());
                        }
                    }
                    Direction::Egress => {
                        if let Some(skel) = &mut self.tc_skel {
                            let _ = skel.maps.tc_src_groups_v6.delete(&gkey);
                            let _ = skel.maps.tc_src_lpm_v6.delete(src_key.as_bytes());
                        }
                    }
                }
                let _ = fs::remove_file(&pin_path);
                match direction {
                    Direction::Ingress => self.ingress_registry.v6.remove(&src_key_bytes),
                    Direction::Egress => self.egress_registry.v6.remove(&src_key_bytes),
                };
            }
        } else {
            inner_map
                .update(dst_key_bytes, val.as_bytes(), MapFlags::ANY)
                .context("update dst LPM v6 after rule removal")?;
        }
        debug!("Deleted policy v6 rule {} ({:?})", rule_id, direction);
        Ok(())
    }

    /// List all IPv4 policy rules as (src_key, dst_key, L4Rule) triples.
    pub fn list_policy_rules_v4(
        &self,
        direction: Direction,
    ) -> Result<Vec<(SrcLpmKeyV4, LpmKeyV4, L4Rule)>> {
        let mut rules = Vec::new();
        let registry = match direction {
            Direction::Ingress => &self.ingress_registry,
            Direction::Egress => &self.egress_registry,
        };
        for (src_key_bytes, (_group_id, pin_path)) in &registry.v4 {
            let mut src_key = SrcLpmKeyV4::default();
            if plain::copy_from_bytes(&mut src_key, src_key_bytes).is_err() {
                continue;
            }
            let inner = match libbpf_rs::MapHandle::from_pinned_path(pin_path) {
                Ok(m) => m,
                Err(e) => {
                    warn!("Could not open inner v4 map from {}: {}", pin_path, e);
                    continue;
                }
            };
            for dst_key_bytes in inner.keys() {
                let mut dst_key = LpmKeyV4::default();
                if plain::copy_from_bytes(&mut dst_key, &dst_key_bytes).is_err() {
                    continue;
                }
                if let Ok(Some(val_bytes)) = inner.lookup(&dst_key_bytes, MapFlags::ANY) {
                    let mut val = DstLpmValue::default();
                    if plain::copy_from_bytes(&mut val, &val_bytes).is_err() {
                        continue;
                    }
                    let count = (val.count as usize).min(MAX_L4_RULES);
                    for i in 0..count {
                        rules.push((src_key, dst_key, val.rules[i]));
                    }
                }
            }
        }
        Ok(rules)
    }


    /// Return the pin directory for inner dst maps of a given direction/AF.
    fn groups_pin_dir(direction: Direction, v6: bool) -> &'static str {
        match (direction, v6) {
            (Direction::Ingress, false) => BPF_GROUPS_V4_INGRESS,
            (Direction::Ingress, true) => BPF_GROUPS_V6_INGRESS,
            (Direction::Egress, false) => BPF_GROUPS_V4_EGRESS,
            (Direction::Egress, true) => BPF_GROUPS_V6_EGRESS,
        }
    }

    /// Add an IPv4 policy rule to the two-level LPM.
    pub fn add_policy_rule_v4(
        &mut self,
        src_key: &SrcLpmKeyV4,
        dst_key: &LpmKeyV4,
        rule: &L4Rule,
        direction: Direction,
    ) -> Result<()> {
        let src_key_bytes = src_key.as_bytes().to_vec();

        // Get existing pin path, or create a new inner map for this source group.
        let existing_pin: Option<String> = match direction {
            Direction::Ingress => self.ingress_registry.v4.get(&src_key_bytes),
            Direction::Egress => self.egress_registry.v4.get(&src_key_bytes),
        }
        .map(|(_, p)| p.clone());

        let mut inner = if let Some(pin_path) = existing_pin {
            libbpf_rs::MapHandle::from_pinned_path(&pin_path)
                .with_context(|| format!("open inner dst v4 map from pin {}", pin_path))?
        } else {
            let group_id = match direction {
                Direction::Ingress => self.ingress_registry.alloc_id(),
                Direction::Egress => self.egress_registry.alloc_id(),
            };
            let mut inner = Self::create_inner_dst_v4(group_id)?;

            // Pin for restart resilience — propagate errors.
            let groups_dir = Self::groups_pin_dir(direction, false);
            fs::create_dir_all(groups_dir)
                .with_context(|| format!("create groups dir {}", groups_dir))?;
            let pin_path = format!("{}/{}", groups_dir, group_id);
            if Path::new(&pin_path).exists() {
                let _ = fs::remove_file(&pin_path);
            }
            inner
                .pin(&pin_path)
                .with_context(|| format!("pin inner dst v4 map to {}", pin_path))?;

            // Register inner map FD in the HASH_OF_MAPS outer map and src LPM.
            let inner_raw = inner.as_fd().as_raw_fd() as u32;
            let gkey = group_id.to_ne_bytes();
            let gval = inner_raw.to_ne_bytes();
            let src_val = SrcLpmValue {
                src_prefixlen: src_key.addr_prefixlen() as u32,
                src_group_id: group_id,
            };
            match direction {
                Direction::Ingress => {
                    if let Some(skel) = &mut self.xdp_skel {
                        skel.maps
                            .src_groups_v4
                            .update(&gkey, &gval, MapFlags::ANY)
                            .context("update src_groups_v4")?;
                        skel.maps
                            .src_lpm_v4
                            .update(src_key.as_bytes(), src_val.as_bytes(), MapFlags::ANY)
                            .context("update src_lpm_v4")?;
                    }
                }
                Direction::Egress => {
                    if let Some(skel) = &mut self.tc_skel {
                        skel.maps
                            .tc_src_groups_v4
                            .update(&gkey, &gval, MapFlags::ANY)
                            .context("update tc_src_groups_v4")?;
                        skel.maps
                            .tc_src_lpm_v4
                            .update(src_key.as_bytes(), src_val.as_bytes(), MapFlags::ANY)
                            .context("update tc_src_lpm_v4")?;
                    }
                }
            }

            match direction {
                Direction::Ingress => self
                    .ingress_registry
                    .v4
                    .insert(src_key_bytes.clone(), (group_id, pin_path)),
                Direction::Egress => self
                    .egress_registry
                    .v4
                    .insert(src_key_bytes.clone(), (group_id, pin_path)),
            };

            inner
        };

        // inner handle is kept open through upsert, then dropped (pin keeps map alive).
        Self::upsert_dst_v4(&mut inner, dst_key, rule)?;
        debug!(
            "Added policy v4 rule {} ({:?}): src={:?} dst={:?}",
            { rule.rule_id },
            direction,
            src_key,
            dst_key
        );
        Ok(())
    }


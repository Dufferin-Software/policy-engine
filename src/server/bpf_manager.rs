    /// Bump per-rule stats from userspace.  Mirrors `tc_update_rule_stats` /
    /// `update_rule_stats` in BPF so inspection paths that match a rule
    /// outside the kernel (currently QUIC SNI) advance the operator-visible
    /// counters the same way TCP SNI and L4 matches do.
    pub fn bump_rule_stats(
        &mut self,
        rule_id: u64,
        direction: Direction,
        pkt_len: u64,
    ) -> Result<()> {
        let map: Option<&dyn MapCore> = match direction {
            Direction::Ingress => self
                .xdp_skel
                .as_ref()
                .map(|s| &s.maps.rule_stats as &dyn MapCore),
            Direction::Egress => self
                .tc_skel
                .as_ref()
                .map(|s| &s.maps.tc_rule_stats as &dyn MapCore),
        };
        let Some(map) = map else { return Ok(()) };

        let key_bytes = rule_id.to_ne_bytes();
        let now_ns = {
            let mut ts = libc::timespec {
                tv_sec: 0,
                tv_nsec: 0,
            };
            unsafe {
                libc::clock_gettime(libc::CLOCK_MONOTONIC, &mut ts);
            }
            (ts.tv_sec as u64) * 1_000_000_000 + (ts.tv_nsec as u64)
        };

        let mut stats = if let Some(existing) = map.lookup(&key_bytes, MapFlags::ANY)? {
            let mut s = RuleStats::default();
            plain::copy_from_bytes(&mut s, &existing)
                .map_err(|e| anyhow!("Failed to parse stats: {:?}", e))?;
            s
        } else {
            RuleStats::default()
        };
        stats.packets = stats.packets.saturating_add(1);
        stats.bytes = stats.bytes.saturating_add(pkt_len);
        stats.last_seen_ns = now_ns;

        map.update(&key_bytes, stats.as_bytes(), MapFlags::ANY)
            .context("Failed to bump rule_stats")?;
        Ok(())
    }


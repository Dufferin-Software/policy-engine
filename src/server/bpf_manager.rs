/// Subdirectory under BPF_PIN_PATH where ingress inner dst LPM maps are pinned
const BPF_GROUPS_V4_INGRESS: &str = "/sys/fs/bpf/policy_engine/groups_v4_in";
const BPF_GROUPS_V6_INGRESS: &str = "/sys/fs/bpf/policy_engine/groups_v6_in";
const BPF_GROUPS_V4_EGRESS: &str = "/sys/fs/bpf/policy_engine/groups_v4_eg";
const BPF_GROUPS_V6_EGRESS: &str = "/sys/fs/bpf/policy_engine/groups_v6_eg";

/// Tracks dynamically-created inner dst LPM trie maps for the two-level LPM.
///
/// Each source prefix group owns one inner BPF_MAP_TYPE_LPM_TRIE that is
/// pinned to the filesystem.  We store only the pin path rather than an open
/// MapHandle so that we never accumulate file descriptors as rules are added
/// (the pinned file keeps the kernel reference alive without an open fd).
struct GroupRegistry {
    /// src_key_bytes → (group_id, pin_path)
    v4: HashMap<Vec<u8>, (u32, String)>,
    v6: HashMap<Vec<u8>, (u32, String)>,
    next_id: u32,
}

impl GroupRegistry {
    fn new() -> Self {
        Self {
            v4: HashMap::new(),
            v6: HashMap::new(),
            next_id: 1,
        }
    }

    fn alloc_id(&mut self) -> u32 {
        let id = self.next_id;
        self.next_id += 1;
        id
    }

    /// Restore a v4 entry from pinned state, bumping next_id as needed.
    fn restore_v4(&mut self, src_key_bytes: Vec<u8>, group_id: u32, pin_path: String) {
        if group_id >= self.next_id {
            self.next_id = group_id + 1;
        }
        self.v4.insert(src_key_bytes, (group_id, pin_path));
    }

    /// Restore a v6 entry from pinned state, bumping next_id as needed.
    fn restore_v6(&mut self, src_key_bytes: Vec<u8>, group_id: u32, pin_path: String) {
        if group_id >= self.next_id {
            self.next_id = group_id + 1;
        }
        self.v6.insert(src_key_bytes, (group_id, pin_path));
    }
}


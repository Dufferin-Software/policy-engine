impl BpfManager {
    /// Resolve interface name from ifindex
    fn ifindex_to_name(ifindex: i32) -> Option<String> {
        let mut buf = [0u8; libc::IF_NAMESIZE];
        let result = unsafe { libc::if_indextoname(ifindex as u32, buf.as_mut_ptr() as *mut i8) };
        if result.is_null() {
            None
        } else {
            let name = unsafe { std::ffi::CStr::from_ptr(buf.as_ptr() as *const i8) };
            name.to_str().ok().map(|s| s.to_string())
        }
    }
}

impl Drop for BpfManager {
    fn drop(&mut self) {
        if self.xdp_skel.is_some() || self.tc_skel.is_some() {
            debug!("BpfManager dropped, pinned BPF programs remain attached");
        }
    }
}


    /// Persist TC egress attachment so it survives server restarts.
    fn store_tc_attachment(ifname: &str) {
        Self::ensure_mode_dir();
        let path = format!("{}/tc_egress_{}", Self::get_mode_dir(), ifname);
        let _ = fs::write(&path, "");
    }

    /// Remove TC egress attachment metadata.
    fn remove_tc_attachment(ifname: &str) {
        let path = format!("{}/tc_egress_{}", Self::get_mode_dir(), ifname);
        let _ = fs::remove_file(&path);
    }

    /// Scan the metadata directory and restore tc_attached for any persisted TC attachments.
    fn restore_tc_attachments(&mut self) {
        let mode_dir = Self::get_mode_dir();
        if let Ok(entries) = fs::read_dir(mode_dir) {
            for entry in entries.flatten() {
                let fname = entry.file_name().to_string_lossy().into_owned();
                if let Some(ifname) = fname.strip_prefix("tc_egress_") {
                    match Self::get_ifindex(ifname) {
                        Ok(ifindex) => {
                            debug!(
                                "Restoring TC egress attachment for {} (ifindex={})",
                                ifname, ifindex
                            );
                            self.tc_attached.insert(ifindex);
                        }
                        Err(_) => {
                            // Interface no longer exists — clean up stale file
                            let _ = fs::remove_file(entry.path());
                        }
                    }
                }
            }
        }
    }

    /// Scan the metadata directory and restore xdp_attached for any persisted XDP attachments.

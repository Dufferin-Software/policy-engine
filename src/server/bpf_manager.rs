    // -------------------------------------------------------------------------
    // BPF version fingerprinting
    // -------------------------------------------------------------------------

    /// Compute a version fingerprint of the embedded BPF ELF data by hashing
    /// the XDP and TC skeleton source files together.
    fn compute_bpf_hash() -> u64 {
        // Feed both skeleton file contents into a single FNV-1a pass with a
        // length separator so that [A][B] and [A+B] produce different hashes.
        const OFFSET: u64 = 14695981039346656037;
        const PRIME: u64 = 1099511628211;
        let mut h = OFFSET;
        for &b in XDP_SKEL_BYTES
            .iter()
            .chain(TC_SKEL_BYTES.len().to_le_bytes().iter())
            .chain(TC_SKEL_BYTES.iter())
        {
            h ^= b as u64;
            h = h.wrapping_mul(PRIME);
        }
        h
    }

    /// Path of the version fingerprint file.
    ///
    /// Stored in the runtime metadata directory (`/var/run/policy_engine/`)
    /// rather than in the BPF filesystem (`/sys/fs/bpf/`) because bpffs only
    /// supports BPF-pinned objects and rejects plain `write()` calls.
    fn bpf_version_path() -> String {
        format!("{}/.bpf_version", Self::get_mode_dir())
    }

    /// On startup: compare the compiled BPF fingerprint against the stored one.
    /// If they differ (or no version file exists while pins do), wipe all pins
    /// so `load_programs` starts with a clean slate.  If they match, existing
    /// pins are reused transparently.  If no pins exist at all, this is a no-op.
    /// Returns `true` if existing pinned maps will be reused (same BPF version,
    /// daemon restart), `false` if this is a fresh start (no pins, reboot, or
    /// BPF version change).
    fn check_version_and_cleanup_if_changed() -> bool {
        let pin_path = Path::new(BPF_PIN_PATH);
        if !pin_path.exists() {
            // Nothing pinned yet — fresh startup, nothing to do.
            return false;
        }

        let current_hash = BpfManager::compute_bpf_hash();
        let version_path = BpfManager::bpf_version_path();

        let needs_cleanup = match fs::read_to_string(&version_path) {
            Ok(stored) => stored.trim().parse::<u64>() != Ok(current_hash),
            Err(_) => {
                // Pins exist but no version file — stale state from before
                // versioning was added; treat as changed.
                true
            }
        };

        if needs_cleanup {
            info!("BPF programs changed or version unknown — clearing pinned state for fresh load");
            BpfManager::cleanup_pinned_state();
            false
        } else {
            info!("BPF programs unchanged, reusing existing pinned state");
            true
        }
    }

    /// Write the current BPF ELF fingerprint to the runtime metadata directory.
    /// Called after programs and maps have been successfully loaded and pinned.
    fn write_bpf_version() {
        let pin_path = Path::new(BPF_PIN_PATH);
        if !pin_path.exists() {
            return;
        }
        BpfManager::ensure_mode_dir();
        let hash = BpfManager::compute_bpf_hash();
        let version_path = BpfManager::bpf_version_path();
        match fs::write(&version_path, hash.to_string()) {
            Ok(()) => debug!("Wrote BPF version fingerprint to {}", version_path),
            Err(e) => warn!("Failed to write BPF version file: {}", e),
        }
    }

    /// Detach our XDP program from any interfaces we previously attached to.
    ///
    /// Reads the `xdp_mode_<ifname>` files from the metadata directory to find
    /// only the interfaces *we* own, so we never disturb programs from other tools.
    /// Must be called BEFORE the metadata directory is removed.
    fn detach_xdp_from_tracked_interfaces() {
        let mode_dir = Self::get_mode_dir();
        let entries = match fs::read_dir(mode_dir) {
            Ok(e) => e,
            Err(_) => return,
        };
        for entry in entries.flatten() {
            let fname = entry.file_name().to_string_lossy().into_owned();
            let ifname = match fname.strip_prefix("xdp_mode_") {
                Some(n) => n.to_string(),
                None => continue,
            };
            let ifindex = match Self::get_ifindex(&ifname) {
                Ok(i) => i,
                Err(_) => continue,
            };

            let mut opts: libbpf_sys::bpf_xdp_query_opts = unsafe { std::mem::zeroed() };
            opts.sz = std::mem::size_of::<libbpf_sys::bpf_xdp_query_opts>() as u64;
            unsafe {
                if libbpf_sys::bpf_xdp_query(ifindex, 0, &mut opts) == 0 && opts.prog_id != 0 {
                    let flags = match opts.attach_mode {
                        1 => 0u32,
                        2 => xdp_flags::XDP_FLAGS_SKB_MODE,
                        3 => xdp_flags::XDP_FLAGS_HW_MODE,
                        _ => 0u32,
                    };
                    let res = libbpf_sys::bpf_xdp_detach(ifindex, flags, std::ptr::null_mut());
                    if res == 0 || res == -2 {
                        info!("Detached stale XDP program from {} during cleanup", ifname);
                    } else {
                        warn!(
                            "Failed to detach XDP from {} during cleanup: {}",
                            ifname, res
                        );
                    }
                }
            }
        }
    }

    /// Remove the TC clsact qdisc from any interfaces we previously attached TC to.
    ///
    /// Reads the `tc_egress_<ifname>` metadata files.
    /// Must be called BEFORE the metadata directory is removed.
    fn detach_tc_from_tracked_interfaces() {
        let mode_dir = Self::get_mode_dir();
        let entries = match fs::read_dir(mode_dir) {
            Ok(e) => e,
            Err(_) => return,
        };
        for entry in entries.flatten() {
            let fname = entry.file_name().to_string_lossy().into_owned();
            let ifname = match fname.strip_prefix("tc_egress_") {
                Some(n) => n.to_string(),
                None => continue,
            };
            let result = std::process::Command::new("tc")
                .args(["qdisc", "del", "dev", &ifname, "clsact"])
                .output();
            match result {
                Ok(o) if o.status.success() => {
                    info!("Removed TC clsact qdisc from {} during cleanup", ifname);
                }
                Ok(o) => {
                    debug!(
                        "tc qdisc del for {} during cleanup: {}",
                        ifname,
                        String::from_utf8_lossy(&o.stderr).trim()
                    );
                }
                Err(e) => {
                    debug!("tc qdisc del for {} failed: {}", ifname, e);
                }
            }
        }
    }

    /// Remove all pinned BPF maps, programs, and runtime metadata.
    ///
    /// This deletes the BPF pin directory (`/sys/fs/bpf/policy_engine`) and the
    /// runtime state directory (`/var/run/policy_engine`).  Pinned map files hold
    /// the kernel's reference to map objects; removing them forces fresh maps to
    /// be created on the next `load_programs` call, which is essential when the
    /// struct layout has changed (e.g. a new statistics field) and the verifier
    /// would otherwise reject the new program for accessing beyond the old
    /// `value_size`.
    ///
    /// Also detaches any running XDP/TC programs we own so that the kernel
    /// immediately stops processing with the old code and the UI shows the
    /// interfaces as unattached, prompting the operator to re-attach with the
    /// new binary.
    pub fn cleanup_pinned_state() {
        // Detach our running programs BEFORE removing the metadata files that
        // tell us which interfaces we own.
        Self::detach_tc_from_tracked_interfaces();
        Self::detach_xdp_from_tracked_interfaces();

        // Remove BPF filesystem pins (maps, programs, links).
        let pin_path = Path::new(BPF_PIN_PATH);
        if pin_path.exists() {
            // Remove inner group map subdirectories first
            for groups_dir in &[
                BPF_GROUPS_V4_INGRESS,
                BPF_GROUPS_V6_INGRESS,
                BPF_GROUPS_V4_EGRESS,
                BPF_GROUPS_V6_EGRESS,
            ] {
                let gpath = Path::new(groups_dir);
                if gpath.exists() {
                    if let Ok(entries) = fs::read_dir(gpath) {
                        for entry in entries.flatten() {
                            let _ = fs::remove_file(entry.path());
                        }
                    }
                    let _ = fs::remove_dir(gpath);
                }
            }
            if let Ok(entries) = fs::read_dir(pin_path) {
                for entry in entries.flatten() {
                    let path = entry.path();
                    if path.is_file() {
                        debug!("Removing pinned BPF object: {:?}", path);
                        let _ = fs::remove_file(&path);
                    }
                }
            }
            // Do not remove the directory itself — it is owned by the
            // policy-engine user and created by tmpfiles.d.  Removing it
            // leaves a root-owned /sys/fs/bpf that the service cannot
            // recreate on the next attach attempt.
            info!(
                "Cleaned up pinned BPF maps and programs from {}",
                BPF_PIN_PATH
            );
        }

        // Remove runtime metadata (TC attachment records, XDP mode files).
        let mode_path = Path::new(Self::get_mode_dir());
        if mode_path.exists() {
            if let Ok(entries) = fs::read_dir(mode_path) {
                for entry in entries.flatten() {
                    let _ = fs::remove_file(entry.path());
                }
            }
            let _ = fs::remove_dir(mode_path);
            info!("Cleaned up runtime metadata from {}", Self::get_mode_dir());
        }
    }

    /// Attach ingress (XDP) program to an interface
    pub fn attach_ingress(&mut self, ifname: &str, mode: XdpMode) -> Result<()> {
        let ifindex = Self::get_ifindex(ifname)?;
        let link_path = Self::get_link_pin_path(ifname);

        let pin_dir = Path::new(BPF_PIN_PATH);
        if !pin_dir.exists() {
            std::fs::create_dir_all(pin_dir).context("Failed to create BPF pin directory")?;
        }

        if Path::new(&link_path).exists() {
            match Link::open(&link_path) {
                Ok(_) => {
                    // Program is already attached in the kernel — idempotent success,
                    // matching attach_tc behaviour.
                    info!(
                        "XDP program already attached to interface {} (pinned link exists) — skipping",
                        ifname
                    );
                    return Ok(());
                }
                Err(_) => {
                    let _ = fs::remove_file(&link_path);
                }
            }
        }

        if self.xdp_attached.contains(&ifindex) {
            info!(
                "XDP program already attached to interface {} — skipping",
                ifname
            );
            return Ok(());
        }

        let skel = self
            .xdp_skel
            .as_mut()
            .ok_or_else(|| anyhow!("XDP skeleton not loaded"))?;

        let prog = &skel.progs.xdp_policy_main;
        let prog_fd = std::os::unix::io::AsRawFd::as_raw_fd(&prog.as_fd());

        let xdp_flags = match mode {
            XdpMode::Native => 0,
            XdpMode::Generic => xdp_flags::XDP_FLAGS_SKB_MODE,
            XdpMode::Offload => xdp_flags::XDP_FLAGS_HW_MODE,
            _ => 0,
        };

        unsafe {
            let res = libbpf_sys::bpf_xdp_attach(ifindex, prog_fd, xdp_flags, std::ptr::null_mut());
            if res != 0 {
                return Err(anyhow!("Failed to attach XDP program: error code {}", res));
            }
        }

        Self::store_xdp_mode(ifname, mode);

        debug!("Attached XDP program via {} mode", mode);

        info!(
            "Attached XDP program to {} (ifindex={}) in {:?} mode",
            ifname, ifindex, mode
        );

        self.xdp_attached.insert(ifindex);

        Ok(())
    }

    /// Detach ingress (XDP) program from an interface
    pub fn detach_ingress(&mut self, ifname: &str) -> Result<()> {
        let ifindex = Self::get_ifindex(ifname)?;

        let mut opts: libbpf_sys::bpf_xdp_query_opts = unsafe { std::mem::zeroed() };
        opts.sz = std::mem::size_of::<libbpf_sys::bpf_xdp_query_opts>() as u64;

        let detach_flags = unsafe {
            let res = libbpf_sys::bpf_xdp_query(ifindex, 0, &mut opts);
            if res != 0 {
                return Err(anyhow!("Failed to query XDP mode before detach"));
            }

            match opts.attach_mode {
                1 => 0u32,
                2 => xdp_flags::XDP_FLAGS_SKB_MODE,
                3 => xdp_flags::XDP_FLAGS_HW_MODE,
                _ => 0u32,
            }
        };

        unsafe {
            let res = libbpf_sys::bpf_xdp_detach(ifindex, detach_flags, std::ptr::null_mut());
            if res != 0 && res != -2 {
                return Err(anyhow!("Failed to detach XDP program: error code {}", res));
            }
        }

        self.xdp_attached.remove(&ifindex);
        Self::remove_xdp_mode(ifname);

        info!("Detached XDP program from {} (ifindex={})", ifname, ifindex);

        Ok(())
    }

    /// Attach egress (TC) program to an interface
    pub fn attach_tc(&mut self, ifname: &str) -> Result<()> {
        let ifindex = Self::get_ifindex(ifname)?;

        if self.tc_attached.contains(&ifindex) {
            info!(
                "TC egress program already attached to {} — skipping",
                ifname
            );
            return Ok(());
        }

        let skel = self
            .tc_skel
            .as_mut()
            .ok_or_else(|| anyhow!("TC skeleton not loaded"))?;

        let prog = &skel.progs.tc_policy_egress;
        let prog_fd = std::os::unix::io::AsRawFd::as_raw_fd(&prog.as_fd());

        // Create clsact qdisc
        let mut hook: libbpf_sys::bpf_tc_hook = unsafe { std::mem::zeroed() };
        hook.sz = std::mem::size_of::<libbpf_sys::bpf_tc_hook>() as u64;
        hook.ifindex = ifindex;
        hook.attach_point = libbpf_sys::BPF_TC_EGRESS;

        unsafe {
            let rc = libbpf_sys::bpf_tc_hook_create(&mut hook);
            // -17 = EEXIST, -16 = EBUSY: clsact qdisc already exists
            // (e.g. created by NetworkManager with exclusivity flag). Both are
            // fine — bpf_tc_attach will still work on the existing qdisc.
            if rc != 0 && rc != -17 && rc != -16 {
                return Err(anyhow!("Failed to create TC hook: error code {}", rc));
            }
        }

        // Attach TC program.
        //
        // Use a fixed priority (1) with BPF_TC_F_REPLACE so attachment is
        // idempotent.  Without BPF_TC_F_REPLACE, a server restart that lost its
        // metadata (e.g. via cleanup_pinned_state) would add a second filter on
        // top of a surviving one, causing every packet to be processed twice.
        //
        // Priority 1 also ensures our filter is evaluated before any stale
        // filters left at the default priority (49152).  Because our program
        // always returns TC_ACT_OK or TC_ACT_SHOT and never TC_ACT_PIPE, the
        // filter chain stops after ours, so stale filters never execute.
        let mut tc_opts: libbpf_sys::bpf_tc_opts = unsafe { std::mem::zeroed() };
        tc_opts.sz = std::mem::size_of::<libbpf_sys::bpf_tc_opts>() as u64;
        tc_opts.prog_fd = prog_fd;
        tc_opts.priority = 1;
        tc_opts.flags = libbpf_sys::BPF_TC_F_REPLACE;

        unsafe {
            let rc = libbpf_sys::bpf_tc_attach(&hook, &mut tc_opts);
            if rc != 0 {
                return Err(anyhow!(
                    "Failed to attach TC egress program: error code {}",
                    rc
                ));
            }
        }

        self.tc_attached.insert(ifindex);
        Self::store_tc_attachment(ifname);
        info!(
            "Attached TC egress program to {} (ifindex={})",
            ifname, ifindex
        );

        // Also attach the TC ingress program so INSPECT-matched flows are
        // cloned to Suricata via bpf_clone_redirect(pe-inspect0).
        // The clsact qdisc (created above) handles both egress and ingress.
        #[cfg(feature = "suricata")]
        {
            let ingress_prog = &skel.progs.tc_policy_ingress;
            let ingress_prog_fd = std::os::unix::io::AsRawFd::as_raw_fd(&ingress_prog.as_fd());

            let mut ingress_hook: libbpf_sys::bpf_tc_hook = unsafe { std::mem::zeroed() };
            ingress_hook.sz = std::mem::size_of::<libbpf_sys::bpf_tc_hook>() as u64;
            ingress_hook.ifindex = ifindex;
            ingress_hook.attach_point = libbpf_sys::BPF_TC_INGRESS;

            let mut tc_ingress_opts: libbpf_sys::bpf_tc_opts = unsafe { std::mem::zeroed() };
            tc_ingress_opts.sz = std::mem::size_of::<libbpf_sys::bpf_tc_opts>() as u64;
            tc_ingress_opts.prog_fd = ingress_prog_fd;
            tc_ingress_opts.priority = 1;
            tc_ingress_opts.flags = libbpf_sys::BPF_TC_F_REPLACE;

            unsafe {
                let rc = libbpf_sys::bpf_tc_attach(&ingress_hook, &mut tc_ingress_opts);
                if rc != 0 {
                    // Non-fatal: egress policy enforcement still works; INSPECT
                    // cloning won't function until the user re-attaches TC.
                    warn!(
                        "Failed to attach TC ingress program to {}: error code {} \
                         (INSPECT cloning disabled)",
                        ifname, rc
                    );
                } else {
                    info!(
                        "Attached TC ingress program to {} (ifindex={})",
                        ifname, ifindex
                    );
                }
            }
        }

        Ok(())
    }

    /// Detach egress (TC) program from an interface
    pub fn detach_tc(&mut self, ifname: &str) -> Result<()> {
        let ifindex = Self::get_ifindex(ifname)?;

        let mut hook: libbpf_sys::bpf_tc_hook = unsafe { std::mem::zeroed() };
        hook.sz = std::mem::size_of::<libbpf_sys::bpf_tc_hook>() as u64;
        hook.ifindex = ifindex;
        hook.attach_point = libbpf_sys::BPF_TC_EGRESS;

        unsafe {
            let rc = libbpf_sys::bpf_tc_hook_destroy(&mut hook);
            // -2 = ENOENT (no hook found, that's fine)
            if rc != 0 && rc != -2 {
                return Err(anyhow!("Failed to destroy TC hook: error code {}", rc));
            }
        }

        self.tc_attached.remove(&ifindex);
        Self::remove_tc_attachment(ifname);
        info!(
            "Detached TC egress program from {} (ifindex={})",
            ifname, ifindex
        );

        Ok(())
    }


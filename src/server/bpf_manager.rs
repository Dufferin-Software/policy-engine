    /// Rebuild the ingress GroupRegistry v4 from the pinned src_lpm_v4 map.
    fn restore_ingress_registry_v4(&mut self) {
        let groups_dir = BPF_GROUPS_V4_INGRESS;
        let skel = match &self.xdp_skel {
            Some(s) => s,
            None => return,
        };
        let keys: Vec<Vec<u8>> = skel.maps.src_lpm_v4.keys().collect();
        for src_key_bytes in keys {
            if let Ok(Some(val_bytes)) = skel.maps.src_lpm_v4.lookup(&src_key_bytes, MapFlags::ANY)
            {
                let mut val = SrcLpmValue {
                    src_prefixlen: 0,
                    src_group_id: 0,
                };
                if plain::copy_from_bytes(&mut val, &val_bytes).is_ok() {
                    let group_id = val.src_group_id;
                    let pin_path = format!("{}/{}", groups_dir, group_id);
                    if Path::new(&pin_path).exists() {
                        debug!("Restoring ingress v4 group {} from {}", group_id, pin_path);
                        self.ingress_registry
                            .restore_v4(src_key_bytes, group_id, pin_path);
                    }
                }
            }
        }
    }


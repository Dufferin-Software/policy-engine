    /// Get all pinned XDP attachments (for show interfaces command)
    pub fn get_pinned_attachments(filter_ifname: Option<&str>) -> Vec<(String, i32, String)> {
        let mut attachments = Vec::new();

        if let Ok(entries) = fs::read_dir("/sys/class/net") {
            for entry in entries.flatten() {
                if let Ok(name) = entry.file_name().into_string() {
                    if crate::types::is_internal_interface(&name) {
                        continue;
                    }
                    if let Some(filter) = filter_ifname {
                        if name != filter {
                            continue;
                        }
                    }

                    if let Ok(ifindex) = Self::get_ifindex(&name) {
                        let mut opts: libbpf_sys::bpf_xdp_query_opts =
                            unsafe { std::mem::zeroed() };
                        opts.sz = std::mem::size_of::<libbpf_sys::bpf_xdp_query_opts>() as u64;

                        unsafe {
                            let res = libbpf_sys::bpf_xdp_query(ifindex, 0, &mut opts);
                            if res == 0 && opts.prog_id != 0 {
                                debug!("Interface {} XDP query: prog_id={}, attach_mode={}, drv_prog_id={}, skb_prog_id={}, hw_prog_id={} ",
                                    name, opts.prog_id, opts.attach_mode, opts.drv_prog_id, opts.skb_prog_id, opts.hw_prog_id);

                                let mode_str = match opts.attach_mode {
                                    1 => "native",
                                    2 => "generic",
                                    3 => "offload",
                                    _ => "unknown",
                                };
                                attachments.push((name, ifindex, mode_str.to_string()));
                            }
                        }
                    }
                }
            }
        }

        attachments
    }


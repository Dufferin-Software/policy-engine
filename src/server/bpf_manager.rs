    /// Read-modify-write a DstLpmValue in an inner v4 dst trie.
    fn upsert_dst_v4(
        inner: &mut libbpf_rs::MapHandle,
        dst_key: &LpmKeyV4,
        rule: &L4Rule,
    ) -> Result<()> {
        let dst_key_bytes = dst_key.as_bytes();
        let mut val = DstLpmValue {
            dst_prefixlen: dst_key.prefixlen,
            ..Default::default()
        };

        // LPM trie lookup is longest-prefix, not exact; scan keys for exact match.
        let key_bytes_vec = dst_key_bytes.to_vec();
        let exact_exists = inner.keys().any(|k| k == key_bytes_vec);
        if exact_exists {
            if let Some(existing) = inner.lookup(dst_key_bytes, MapFlags::ANY)? {
                plain::copy_from_bytes(&mut val, &existing)
                    .map_err(|e| anyhow!("Failed to parse DstLpmValue: {:?}", e))?;
            }
        }

        let count = val.count as usize;
        if let Some(pos) = val.rules[..count]
            .iter()
            .position(|r| r.rule_id == rule.rule_id)
        {
            val.rules[pos] = *rule;
        } else if count < MAX_L4_RULES {
            val.rules[count] = *rule;
            val.count += 1;
        } else {
            anyhow::bail!("Too many L4 rules for dst prefix (max {})", MAX_L4_RULES);
        }
        inner
            .update(dst_key_bytes, val.as_bytes(), MapFlags::ANY)
            .context("update dst LPM v4 entry")?;
        Ok(())
    }


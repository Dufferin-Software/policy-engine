    /// Get statistics for a rule.
    ///
    /// The dataplane only writes rule_stats on the cache-miss path; traffic on
    /// cached flows accumulates in flow_verdict_cache entries instead, so fold
    /// those in first (rate-limited — one cache walk covers a whole burst of
    /// per-rule reads like the metrics tick or a UI rule listing).
    pub fn get_rule_stats(&self, rule_id: u64, direction: Direction) -> Result<Option<RuleStats>> {
        self.harvest_rule_stats_rate_limited(direction);
        let map: Option<&dyn MapCore> = match direction {
            Direction::Ingress => self
                .xdp_skel
                .as_ref()
                .map(|s| &s.maps.rule_stats as &dyn MapCore),
            Direction::Egress => self
                .tc_skel
                .as_ref()
                .map(|s| &s.maps.tc_rule_stats as &dyn MapCore),
        };

        if let Some(map) = map {
            let key_bytes = rule_id.to_ne_bytes();

            if let Some(value_bytes) = map.lookup(&key_bytes, MapFlags::ANY)? {
                let mut stats = RuleStats::default();
                plain::copy_from_bytes(&mut stats, &value_bytes)
                    .map_err(|e| anyhow!("Failed to parse stats: {:?}", e))?;
                return Ok(Some(stats));
            }
        }

        Ok(None)
    }

    /// Get global statistics for an interface
    pub fn get_global_stats(&self, ifindex: u32, direction: Direction) -> Result<GlobalStats> {
        let mut total_stats = GlobalStats::default();
        let key = (ifindex % MAX_INTERFACES).to_ne_bytes();

        let map: Option<&dyn MapCore> = match direction {
            Direction::Ingress => self
                .xdp_skel
                .as_ref()
                .map(|s| &s.maps.global_stats as &dyn MapCore),
            Direction::Egress => self
                .tc_skel
                .as_ref()
                .map(|s| &s.maps.tc_global_stats as &dyn MapCore),
        };

        if let Some(map) = map {
            if let Some(values) = map.lookup_percpu(&key, MapFlags::ANY)? {
                for cpu_value in values {
                    let mut stats = GlobalStats::default();
                    plain::copy_from_bytes(&mut stats, &cpu_value)
                        .map_err(|e| anyhow!("Failed to parse stats: {:?}", e))?;
                    total_stats.accumulate(&stats);
                }
            }
        }

        Ok(total_stats)
    }

    /// Sum global_stats across all interface slots and CPUs for a direction.
    /// Backs the l3/quic/proc_hist getters, which report engine-wide totals
    /// for counters that are tracked per-interface inside struct global_stats.
    fn sum_global_stats(&self, direction: Direction) -> Result<GlobalStats> {
        let mut total_stats = GlobalStats::default();
        let map: Option<&dyn MapCore> = match direction {
            Direction::Ingress => self
                .xdp_skel
                .as_ref()
                .map(|s| &s.maps.global_stats as &dyn MapCore),
            Direction::Egress => self
                .tc_skel
                .as_ref()
                .map(|s| &s.maps.tc_global_stats as &dyn MapCore),
        };

        if let Some(map) = map {
            for ifslot in 0..MAX_INTERFACES {
                let key = ifslot.to_ne_bytes();
                if let Some(values) = map.lookup_percpu(&key, MapFlags::ANY)? {
                    for cpu_value in values {
                        let mut stats = GlobalStats::default();
                        plain::copy_from_bytes(&mut stats, &cpu_value)
                            .map_err(|e| anyhow!("Failed to parse stats: {:?}", e))?;
                        total_stats.accumulate(&stats);
                    }
                }
            }
        }

        Ok(total_stats)
    }

    /// Get processing-time histogram buckets (64 entries, summed across CPUs
    /// and interfaces)
    pub fn get_processing_time_hist(&self, direction: Direction) -> Result<Vec<u64>> {
        Ok(self.sum_global_stats(direction)?.proc_hist.to_vec())
    }


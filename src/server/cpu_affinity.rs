    fn test_double_attach_needs_two_detaches() {
        let mock = mock_capture_eth0("10", "rx-0");
        let mut store = NicAffinityStore::new();
        store.on_attach("eth0", &mock);
        let mock2 = MockNicSysIo::new();
        store.on_attach("eth0", &mock2);

        // First detach: ref 2→1, no snapshot yet.
        assert!(store.on_detach("eth0").is_none());
        assert_eq!(store.inner["eth0"].1, 1);

        // Second detach: ref 1→0, snapshot returned.
        assert!(store.on_detach("eth0").is_some());
        assert!(store.inner.is_empty());
    }


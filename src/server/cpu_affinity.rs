//! CPU-affinity helpers for the policy-engine server.
//!
//! All OS-level calls live here; the rest of the crate stays pure and testable.
//!
//! The [`NicSysIo`] trait abstracts every `/proc` / `/sys` interaction so
//! tests can inject a mock without needing root or real network interfaces.
//! Production code uses [`DefaultNicSysIo`].

use std::collections::HashMap;

// ---------------------------------------------------------------------------
// Thread pinning
// ---------------------------------------------------------------------------

/// Pin the calling thread to the first CPU in `cpus`.
///
/// Best-effort: logs a warning on failure but never panics.
pub fn pin_thread_to_cpus(cpus: &[usize]) {
    if let Some(&cpu) = cpus.first() {
        if !core_affinity::set_for_current(core_affinity::CoreId { id: cpu }) {
            log::warn!("cpu_affinity: failed to pin thread to CPU {cpu}");
        }
    }
}

/// Pin the calling thread to `cpus[index % cpus.len()]`.
///
/// Used from a tokio `on_thread_start` callback with an `AtomicUsize` counter
/// so consecutive Tokio workers are spread across `cpus` in round-robin order.
pub fn pin_thread_by_index(cpus: &[usize], index: usize) {
    if !cpus.is_empty() {
        pin_thread_to_cpus(&[cpus[index % cpus.len()]]);
    }
}

// ---------------------------------------------------------------------------
// NicSysIo trait — all /proc + /sys interactions
// ---------------------------------------------------------------------------

/// Abstracts every filesystem interaction needed by the NIC affinity helpers.
///
/// The real implementation is [`DefaultNicSysIo`].  Tests inject
/// [`MockNicSysIo`] (generated by `mockall` in test builds).
#[cfg_attr(test, mockall::automock)]
pub trait NicSysIo: Send + Sync {
    /// Read the full content of `/proc/interrupts`.
    fn read_interrupts(&self) -> Option<String>;

    /// Read `/proc/irq/{irq}/smp_affinity_list`, trimming trailing whitespace.
    fn read_affinity_list(&self, irq: &str) -> Option<String>;

    /// Write `value` to `/proc/irq/{irq}/smp_affinity_list`.
    /// Returns `true` on success.
    fn write_affinity_list(&self, irq: &str, value: &str) -> bool;

    /// Return the names of all `rx-*` entries under
    /// `/sys/class/net/{ifname}/queues/`.
    fn list_rx_queues(&self, ifname: &str) -> Vec<String>;

    /// Read `/sys/class/net/{ifname}/queues/{queue}/rps_cpus`, trimming
    /// trailing whitespace.
    fn read_rps_cpus(&self, ifname: &str, queue: &str) -> Option<String>;

    /// Write `value` to `/sys/class/net/{ifname}/queues/{queue}/rps_cpus`.
    /// Returns `true` on success.
    fn write_rps_cpus(&self, ifname: &str, queue: &str, value: &str) -> bool;
}

/// Production implementation of [`NicSysIo`] that performs real filesystem I/O.
pub struct DefaultNicSysIo;

impl NicSysIo for DefaultNicSysIo {
    fn read_interrupts(&self) -> Option<String> {
        std::fs::read_to_string("/proc/interrupts").ok()
    }

    fn read_affinity_list(&self, irq: &str) -> Option<String> {
        let path = format!("/proc/irq/{irq}/smp_affinity_list");
        std::fs::read_to_string(&path)
            .ok()
            .map(|s| s.trim_end().to_string())
    }

    fn write_affinity_list(&self, irq: &str, value: &str) -> bool {
        let path = format!("/proc/irq/{irq}/smp_affinity_list");
        if let Err(e) = std::fs::write(&path, value) {
            log::warn!("cpu_affinity: could not write {path}: {e}");
            false
        } else {
            true
        }
    }

    fn list_rx_queues(&self, ifname: &str) -> Vec<String> {
        let dir = format!("/sys/class/net/{ifname}/queues");
        match std::fs::read_dir(&dir) {
            Ok(entries) => entries
                .flatten()
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .filter(|n| n.starts_with("rx-"))
                .collect(),
            Err(e) => {
                log::warn!("cpu_affinity: could not read {dir}: {e}");
                vec![]
            }
        }
    }

    fn read_rps_cpus(&self, ifname: &str, queue: &str) -> Option<String> {
        let path = format!("/sys/class/net/{ifname}/queues/{queue}/rps_cpus");
        std::fs::read_to_string(&path)
            .ok()
            .map(|s| s.trim_end().to_string())
    }

    fn write_rps_cpus(&self, ifname: &str, queue: &str, value: &str) -> bool {
        let path = format!("/sys/class/net/{ifname}/queues/{queue}/rps_cpus");
        if let Err(e) = std::fs::write(&path, value) {
            log::warn!("cpu_affinity: could not write {path}: {e}");
            false
        } else {
            true
        }
    }
}

// ---------------------------------------------------------------------------
// NIC IRQ / RPS affinity — apply, capture, restore
// ---------------------------------------------------------------------------

/// Saved IRQ/RPS affinity state for one interface, captured before we changed it.
#[derive(Debug, Clone, Default)]
pub struct NicAffinitySnapshot {
    /// IRQ number string → content of `/proc/irq/{N}/smp_affinity_list` before our change.
    pub irq_lists: HashMap<String, String>,
    /// Queue name (e.g. `"rx-0"`) → content of its `rps_cpus` file before our change.
    pub rps_queues: HashMap<String, String>,
}

/// Per-interface snapshot store with attach/detach reference counting.
///
/// - First `on_attach` for an interface captures the current NIC affinity (ref = 1).
/// - Subsequent `on_attach` calls for the same interface just increment the ref.
/// - `on_detach` decrements the ref; when it hits zero the snapshot is returned for restoration.
/// - `drain_all` removes every interface (used by `detach_all`).
#[derive(Debug, Default)]
pub struct NicAffinityStore {
    inner: HashMap<String, (NicAffinitySnapshot, usize)>,
}

impl NicAffinityStore {
    pub fn new() -> Self {
        Self::default()
    }

    /// Called before applying NIC affinity on attach.
    ///
    /// Captures the current settings on the first attach for this interface
    /// (using `io` to read `/proc` and `/sys`); only increments the ref on
    /// subsequent attaches of the same interface.
    pub fn on_attach(&mut self, ifname: &str, io: &dyn NicSysIo) {
        match self.inner.entry(ifname.to_string()) {
            std::collections::hash_map::Entry::Occupied(mut e) => {
                e.get_mut().1 += 1;
            }
            std::collections::hash_map::Entry::Vacant(v) => {
                let snapshot = capture_nic_affinity(ifname, io);
                v.insert((snapshot, 1));
            }
        }
    }

    /// Called after a successful detach.
    ///
    /// Decrements the ref for `ifname`; when it reaches zero the snapshot is removed
    /// and returned to the caller for restoration.
    pub fn on_detach(&mut self, ifname: &str) -> Option<NicAffinitySnapshot> {
        if let Some(entry) = self.inner.get_mut(ifname) {
            entry.1 = entry.1.saturating_sub(1);
            if entry.1 == 0 {
                return self.inner.remove(ifname).map(|(snap, _)| snap);
            }
        }
        None
    }

    /// Remove all interface snapshots and return them (used by `detach_all`).
    pub fn drain_all(&mut self) -> Vec<(String, NicAffinitySnapshot)> {
        self.inner.drain().map(|(k, (snap, _))| (k, snap)).collect()
    }
}

/// Steer NIC IRQs and software RPS for `ifname` onto `cpus`.
///
/// 1. Parses `/proc/interrupts` for IRQ numbers whose description contains
///    `ifname` and writes a CPU-list string to `/proc/irq/{N}/smp_affinity_list`.
/// 2. Writes a hex CPU-mask to every
///    `/sys/class/net/{ifname}/queues/rx-*/rps_cpus` file (software RPS).
///
/// All failures are logged but never fatal.
pub fn apply_nic_affinity(ifname: &str, cpus: &[usize], io: &dyn NicSysIo) {
    if cpus.is_empty() {
        return;
    }
    let cpu_list = format_cpu_list(cpus);
    let cpu_mask = cpu_list_to_hex_mask(cpus);

    // Hardware IRQ steering
    if let Some(content) = io.read_interrupts() {
        for (irq, _) in irqs_for_iface(&content, ifname) {
            if io.write_affinity_list(&irq, &cpu_list) {
                log::info!("cpu_affinity: IRQ {irq} ({ifname}) → CPUs {cpu_list}");
            }
        }
    } else {
        log::warn!("cpu_affinity: could not read /proc/interrupts");
    }

    // Software RPS
    for queue in io.list_rx_queues(ifname) {
        if io.write_rps_cpus(ifname, &queue, &cpu_mask) {
            log::info!("cpu_affinity: RPS {ifname}/{queue} → mask {cpu_mask}");
        }
    }
}

/// Restore NIC affinity to the state captured in `snapshot`.
///
/// Writes the saved `smp_affinity_list` and `rps_cpus` values back.
/// All failures are logged but never fatal.
pub fn restore_nic_affinity(ifname: &str, snapshot: &NicAffinitySnapshot, io: &dyn NicSysIo) {
    for (irq, original) in &snapshot.irq_lists {
        if io.write_affinity_list(irq, original) {
            log::info!("cpu_affinity: restored IRQ {irq} ({ifname}) → {original}");
        }
    }
    for (queue, original) in &snapshot.rps_queues {
        if io.write_rps_cpus(ifname, queue, original) {
            log::info!("cpu_affinity: restored RPS {ifname}/{queue} → {original}");
        }
    }
}

// ---------------------------------------------------------------------------
// Private: read current NIC affinity into a snapshot
// ---------------------------------------------------------------------------

fn capture_nic_affinity(ifname: &str, io: &dyn NicSysIo) -> NicAffinitySnapshot {
    let mut snapshot = NicAffinitySnapshot::default();

    if let Some(content) = io.read_interrupts() {
        for (irq, _) in irqs_for_iface(&content, ifname) {
            if let Some(val) = io.read_affinity_list(&irq) {
                snapshot.irq_lists.insert(irq, val);
            }
        }
    }

    for queue in io.list_rx_queues(ifname) {
        if let Some(val) = io.read_rps_cpus(ifname, &queue) {
            snapshot.rps_queues.insert(queue, val);
        }
    }

    snapshot
}

/// Parse `/proc/interrupts` content and return `(irq_nr, description)` pairs
/// whose description contains `ifname`.
fn irqs_for_iface<'a>(content: &'a str, ifname: &str) -> impl Iterator<Item = (String, &'a str)> {
    content
        .lines()
        .filter_map(|line| {
            let trimmed = line.trim_start();
            let colon = trimmed.find(':')?;
            let irq = trimmed[..colon].trim().to_string();
            let desc = &trimmed[colon + 1..];
            if desc.contains(ifname) {
                Some((irq, desc))
            } else {
                None
            }
        })
        .collect::<Vec<_>>()
        .into_iter()
}


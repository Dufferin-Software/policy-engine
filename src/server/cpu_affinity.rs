        // mock_capture_eth0 uses `.once()` — a second capture would panic.
        let mock = mock_capture_eth0("10", "rx-0");
        let mut store = NicAffinityStore::new();
        store.on_attach("eth0", &mock);
        // Second attach: mock has no more expectations, so no IO calls expected.

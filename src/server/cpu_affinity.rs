/// Convert a CPU list to a compact string suitable for `smp_affinity_list`.
///
/// Consecutive CPUs are collapsed into ranges, non-consecutive are joined with commas.
/// Examples: `[2, 3, 4]` → `"2-4"`, `[0, 2, 4]` → `"0,2,4"`, `[0]` → `"0"`.
fn format_cpu_list(cpus: &[usize]) -> String {
    if cpus.is_empty() {
        return String::new();
    }
    let mut sorted = cpus.to_vec();
    sorted.sort_unstable();
    sorted.dedup();

    let mut parts: Vec<String> = Vec::new();
    let mut range_start = sorted[0];
    let mut range_end = sorted[0];

    for &cpu in &sorted[1..] {
        if cpu == range_end + 1 {
            range_end = cpu;
        } else {
            if range_start == range_end {
                parts.push(range_start.to_string());
            } else {
                parts.push(format!("{range_start}-{range_end}"));
            }
            range_start = cpu;
            range_end = cpu;
        }
    }
    if range_start == range_end {
        parts.push(range_start.to_string());
    } else {
        parts.push(format!("{range_start}-{range_end}"));
    }

    parts.join(",")
}

/// Convert a CPU list to a hex bitmask string (no `0x` prefix) for `rps_cpus`.
///
/// Examples: `[0]` → `"1"`, `[0, 1]` → `"3"`, `[2]` → `"4"`.
fn cpu_list_to_hex_mask(cpus: &[usize]) -> String {
    let mut mask: u64 = 0;
    for &cpu in cpus {
        if cpu < 64 {
            mask |= 1u64 << cpu;
        }
    }
    format!("{mask:x}")
}


export function getPortName(protocol: "tcp" | "udp", port: number): string {
  const mappings = protocol === "tcp" ? tcpMappings : udpMappings;
  for (const [start, end, name] of mappings) {
    if (port >= start && port <= end) {
      return name;
    }
  }
  return "unknown";
}
